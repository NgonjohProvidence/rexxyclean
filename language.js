    const normalizedTranslations = Object.fromEntries(
        Object.entries(translations).map(([source, translated]) => [source.trim(), translated.trim()])
    );
    const originalTextNodes = new WeakMap();

    const setLanguage = language => {
        const french = language === "fr";
        document.documentElement.lang = french ? "fr" : "en";

        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        let node;
        while ((node = walker.nextNode())) {
            if (!originalTextNodes.has(node)) {
                originalTextNodes.set(node, node.nodeValue);
            }
            const original = originalTextNodes.get(node);
            const trimmed = original.trim();
            if (!trimmed) {
                continue;
            }

            let translated = normalizedTranslations[trimmed];
            if (trimmed === "to" && node.parentElement?.closest("#about-spaces-heading")) {
                translated = "jusqu’au";
            }
            if (!translated) {
                const hourlyEstimate = trimmed.match(/^For example, ([\d.]+) hours with (\d+) cleaners at (CAD) ([\d,.]+) per cleaner-hour gives an estimated service subtotal of (CAD) ([\d,.]+) before optional extras\.$/);
                if (hourlyEstimate) {
                    translated = `Par exemple, ${hourlyEstimate[1].replace(".", ",")} heures avec ${hourlyEstimate[2]} préposés à ${hourlyEstimate[3]} ${hourlyEstimate[4]} par heure de travail donnent un sous-total estimé de ${hourlyEstimate[5]} ${hourlyEstimate[6]} avant les options.`;
                }
            }
            if (!translated) {
                const rate = trimmed.match(/^(CAD) ([\d,.]+) per cleaner-hour$/);
                if (rate) {
                    translated = `${rate[2]} ${rate[1]} par heure de travail d’un préposé`;
                }
            }
            node.nodeValue = french && translated
                ? original.replace(trimmed, translated)
                : original;
        }

        document.querySelectorAll("[aria-label], [alt], [placeholder], [title]").forEach(element => {
            for (const attribute of ["aria-label", "alt", "placeholder", "title"]) {
                const value = element.getAttribute(attribute);
                if (!value) {
                    continue;
                }
                const key = `original-${attribute}`;
                if (!element.hasAttribute(`data-${key}`)) {
                    element.setAttribute(`data-${key}`, value);
                }
                const original = element.getAttribute(`data-${key}`);
                element.setAttribute(attribute, french ? (attributeTranslations[original] || translations[original] || original) : original);
            }
        });

        const title = document.title;
        const titles = {
            "About Bexxy — Bexxy Care and Clean": "À propos de Bexxy — Bexxy Care and Clean",
            "Cleaning prices — Bexxy Care and Clean": "Tarifs de nettoyage — Bexxy Care and Clean",
            "Book a cleaning — Bexxy Care and Clean": "Réserver un nettoyage — Bexxy Care and Clean",
            "Privacy notice — Bexxy Care and Clean": "Avis de confidentialité — Bexxy Care and Clean",
            "Bexxy Care and Clean — Ottawa & Gatineau": "Bexxy Care and Clean — Ottawa et Gatineau"
        };
        document.title = french ? (titles[title] || title) : (Object.keys(titles).find(key => titles[key] === title) || title);

        document.querySelectorAll('meta[name="description"]').forEach(meta => {
            const original = meta.dataset.originalContent || meta.content;
            if (!meta.dataset.originalContent) {
                meta.dataset.originalContent = original;
            }
            meta.content = french ? (attributeTranslations[original] || original) : original;
        });

        document.querySelectorAll('a[href^="receipt.php"]').forEach(link => {
            link.href = `receipt.php?lang=${language}`;
        });

        document.querySelectorAll("[data-language]").forEach(button => {
            button.setAttribute("aria-pressed", button.dataset.language === language ? "true" : "false");
        });
    };

    const start = () => {
        const header = document.querySelector(".site-header");
        if (header && !document.querySelector(".language-switch")) {
            const switcher = document.createElement("div");
            switcher.className = "language-switch";
            switcher.setAttribute("role", "group");
            switcher.setAttribute("aria-label", "Choose language / Choisir la langue");
            switcher.innerHTML = '<button type="button" data-language="en" aria-label="English">EN</button><button type="button" data-language="fr" aria-label="Français">FR</button>';
            const navigation = header.querySelector(".primary-nav");
            if (navigation) {
                navigation.append(switcher);
            } else {
                header.append(switcher);
            }
            switcher.addEventListener("click", event => {
                const button = event.target.closest("button[data-language]");
                if (!button) {
                    return;
                }
                const language = button.dataset.language;
                try {
                    localStorage.setItem("bexxy-language", language);
                } catch (error) {
                    console.error("Could not save the selected language.", error);
                }
                setLanguage(language);
            });
        }

        let language = "en";
        try {
            language = localStorage.getItem("bexxy-language") === "fr" ? "fr" : "en";
        } catch (error) {
            console.error("Could not read the saved language preference.", error);
        }
        setLanguage(language);
    };

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", start, { once: true });
    } else {
        start();
    }
